#!/usr/bin/env node
/*
 * Builds the Novel font de-obfuscation runtime that ships as
 * resources/rawfile/novel-font-deobfuscation.js.
 *
 * Some Chinese novel sites defeat text extraction by replacing every content
 * character with a rare CJK codepoint and then drawing the real glyph with a
 * per-response @font-face. The served bytes are valid UTF-8, so this is not an
 * encoding problem: the page is readable only because the font maps those
 * codepoints back to real glyphs. The runtime below recovers that mapping by
 * Brotli-decoding the page's own WOFF2 and reading its `cmap` and `post`
 * tables: `cmap` gives codepoint -> glyph id and `post` gives glyph id ->
 * glyph name, and the generated fonts name each glyph `uniXXXX` for the real
 * character.
 *
 * Why a JS bundle instead of native: HarmonyOS `@ohos.zlib` has no Brotli and
 * Chromium does not implement `DecompressionStream('brotli')`, so the decode
 * has to be bundled. Running in the page also means the font fetch inherits the
 * page's own origin and cookies.
 *
 * Provenance (pinned):
 *   brotli@1.3.3        MIT          https://github.com/devongovett/brotli.js
 *     Its static dictionary files carry Google's Apache-2.0 header.
 *   base64-js@1.5.1     MIT          https://github.com/beatgammit/base64-js
 *
 * Usage: node scripts/build-novel-font-deobfuscator.js
 *   Reads the two packages from npm, writes the bundle, prints size + sha256.
 *   The generated file is committed; this script exists so it is reproducible.
 */

'use strict';

const fs = require('fs');
const os = require('os');
const path = require('path');
const crypto = require('crypto');
const { execFileSync } = require('child_process');

const BROTLI_VERSION = '1.3.3';
const BASE64_JS_VERSION = '1.5.1';
const OUTPUT_REL = 'AiraBrowser/entry/src/main/resources/rawfile/novel-font-deobfuscation.js';
const BUNDLE_VERSION = 'aira-novel-font-1';

const REPO_ROOT = path.resolve(__dirname, '..');
const OUTPUT_PATH = path.join(REPO_ROOT, OUTPUT_REL);

// Brotli's Node-oriented entry points reach for `fs`/`Buffer`; the browser build
// swaps the 756 KB JSON dictionary for the 69 KB Brotli-compressed one.
function collectSources(packageDir) {
  const brotliDir = path.join(packageDir, 'brotli', 'package');
  const base64Dir = path.join(packageDir, 'base64-js', 'package');
  const files = [
    ['dec/bit_reader.js', path.join(brotliDir, 'dec', 'bit_reader.js')],
    ['dec/context.js', path.join(brotliDir, 'dec', 'context.js')],
    ['dec/huffman.js', path.join(brotliDir, 'dec', 'huffman.js')],
    ['dec/prefix.js', path.join(brotliDir, 'dec', 'prefix.js')],
    ['dec/transform.js', path.join(brotliDir, 'dec', 'transform.js')],
    ['dec/dictionary.js', path.join(brotliDir, 'dec', 'dictionary.js')],
    ['dec/dictionary-browser.js', path.join(brotliDir, 'dec', 'dictionary-browser.js')],
    ['dec/dictionary.bin.js', path.join(brotliDir, 'dec', 'dictionary.bin.js')],
    ['dec/streams.js', path.join(brotliDir, 'dec', 'streams.js')],
    ['dec/decode.js', path.join(brotliDir, 'dec', 'decode.js')],
    ['base64-js', path.join(base64Dir, 'index.js')]
  ];
  for (const [id, file] of files) {
    if (!fs.existsSync(file)) {
      throw new Error(`Missing vendored source for ${id}: ${file}`);
    }
  }
  // `dec/dictionary.js` requires the huge JSON dictionary directly; the browser
  // build aliases it to the compressed variant. Alias it here so the decode
  // paths are identical to what brotli.js ships for browsers.
  const aliases = { 'dec/dictionary-data': 'dec/dictionary-browser' };
  return { files, aliases };
}

function wrapModule(id, source) {
  return `modules[${JSON.stringify(id)}] = function(module, exports, require){\n${source}\n};\n`;
}

function buildBundle(sources) {
  const { files, aliases } = sources;
  const sorted = files.slice().sort((a, b) => (a[0] < b[0] ? -1 : 1));
  let registry = '';
  for (const [id, file] of sorted) {
    // Register without the extension: the vendored sources `require` each other
    // as './decode', so both the registry key and the lookup drop '.js'.
    registry += wrapModule(id.replace(/\.js$/, ''), fs.readFileSync(file, 'utf8'));
  }

  const appApi = fs.readFileSync(path.join(__dirname, 'lib', 'novel-font-deobfuscation-api.js'), 'utf8');

  return `/* Generated by scripts/build-novel-font-deobfuscator.js - do not edit.
 * ${BUNDLE_VERSION}
 * brotli.js ${BROTLI_VERSION} (MIT; dictionary files Apache-2.0, Google Inc.)
 * base64-js ${BASE64_JS_VERSION} (MIT)
 * See resources/rawfile/novel-font-deobfuscation-LICENSE.txt for the full texts.
 */
(function(global){
'use strict';
var modules = {};
var cache = {};
var alias = ${JSON.stringify(aliases)};
function normalize(id, from){
  if (id.charAt(0) !== '.'){ return id.replace(/\\.js$/, ''); }
  var parts = from.split('/'); parts.pop();
  var segs = id.split('/');
  for (var i = 0; i < segs.length; i++){
    var s = segs[i];
    if (s === '.' || s === ''){ continue; }
    if (s === '..'){ parts.pop(); } else { parts.push(s); }
  }
  return parts.join('/').replace(/\\.js$/, '');
}
function airaRequire(id, from){
  var key = normalize(id, from || '');
  if (Object.prototype.hasOwnProperty.call(alias, key)){ key = alias[key]; }
  if (Object.prototype.hasOwnProperty.call(cache, key)){ return cache[key].exports; }
  if (!Object.prototype.hasOwnProperty.call(modules, key)){
    throw new Error('aira novel font: unknown module ' + key);
  }
  var module = { exports: {} };
  cache[key] = module;
  modules[key](module, module.exports, function(child){ return airaRequire(child, key); });
  return module.exports;
}
${registry}
${appApi}
})(typeof window !== 'undefined' ? window : this);
`;
}

function fetchPackages(tmpDir) {
  execFileSync('npm', ['pack', `brotli@${BROTLI_VERSION}`, `base64-js@${BASE64_JS_VERSION}`, '--silent'],
    { cwd: tmpDir, stdio: ['ignore', 'ignore', 'inherit'] });
  for (const [name, file] of [['brotli', `brotli-${BROTLI_VERSION}.tgz`],
    ['base64-js', `base64-js-${BASE64_JS_VERSION}.tgz`]]) {
    const dir = path.join(tmpDir, name);
    fs.mkdirSync(dir, { recursive: true });
    execFileSync('tar', ['xzf', path.join(tmpDir, file), '-C', dir], { stdio: 'inherit' });
  }
}

function main() {
  const tmpDir = fs.mkdtempSync(path.join(os.tmpdir(), 'aira-novel-font-'));
  try {
    fetchPackages(tmpDir);
    const bundle = buildBundle(collectSources(tmpDir));
    fs.writeFileSync(OUTPUT_PATH, bundle);
    const sha = crypto.createHash('sha256').update(bundle).digest('hex');
    process.stdout.write(`Wrote ${OUTPUT_REL}\n`);
    process.stdout.write(`  bytes:  ${Buffer.byteLength(bundle)}\n`);
    process.stdout.write(`  sha256: ${sha}\n`);
  } finally {
    fs.rmSync(tmpDir, { recursive: true, force: true });
  }
}

main();
